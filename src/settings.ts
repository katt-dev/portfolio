export type Lang = "ru" | "en";
export interface TextPair { ru: string; en: string }
export interface ProjectImage { src: string; caption: TextPair }

// Ссылка на площадку, где лежит игра. Их может быть сколько угодно:
// Steam, itch.io, Google Play, свой сайт — подпись пишешь сам.
export interface ProjectLink {
  url: string;      // адрес страницы
  label: TextPair;  // надпись на кнопке (ru / en)
}
export interface TeamMember {
  name: string;
  role: TextPair;
  avatar: string;   // пусто "" -> аватарка не показывается
  email?: string;   // пусто "" или нет поля -> кнопка «написать» скрыта
}

// Стадия проекта. Сам список стадий — в блоке 3 ниже (STATUS).
// Тип берётся оттуда автоматически: добавил строку в STATUS — стадия сразу
// доступна и в проектах, и в выпадающем списке редактора.
// Пусто "" -> плашка со стадией не показывается.
export type StatusKey = keyof typeof STATUS;
export type ProjectStatus = "" | StatusKey;

// Как показывать обложку и скриншоты проекта:
//   "auto"   — картинка видна ЦЕЛИКОМ, ничего не обрезается, высота
//              подстраивается под саму картинку и под размер окна;
//   "custom" — жёсткий формат 16:10, картинка заполняет блок и обрезается
//              по краям (так ты сам решаешь, какой кадр показать).
export type ImageFit = "auto" | "custom";

export interface Project {
  id: string;
  num: string;
  year: string;
  engine: string;
  status: ProjectStatus;
  imageFit: ImageFit;
  tags: string[];
  cover: string;
  title: TextPair;
  subtitle: TextPair;
  description: TextPair;
  myRole: TextPair;

  // ССЫЛКИ НА ПЛОЩАДКИ (Steam, itch.io, Google Play, свой сайт…).
  // Сколько ссылок — столько кнопок в окне проекта. Пустой список = кнопок нет.
  links: ProjectLink[];

  images: ProjectImage[];
  team: TeamMember[];
}


